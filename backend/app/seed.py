def _add_topic(db: Session, subject: Subject, parent: Topic, order: int, data: dict) -> None:
    topic = Topic(subject=subject, parent_topic=parent, title_ru=data["title_ru"], title_tj=data["title_tj"], order=order)
    db.add(topic)
    lesson = Lesson(topic=topic, language=Language.RUSSIAN, title=data["title_ru"], content=data["lesson"], order=1)
    db.add(lesson)
    if data.get("lesson_tj"):
        db.add(Lesson(topic=topic, language=Language.TAJIK, title=data["title_tj"], content=data["lesson_tj"], order=1))
    for i, item in enumerate(data.get("check", [])):
        db.add(_question(item, i, topic=topic, lesson=lesson))
    for i, item in enumerate(data.get("test", [])):
        db.add(_question(item, i, topic=topic))


def _question(item: dict, order: int, **links) -> Question:
    return Question(
        text=item["text"],
        options=item["options"],
        correct_option_index=item["correct"],
        explanation=item["explanation"],
        difficulty=Difficulty(item["difficulty"]),
        language=Language.RUSSIAN,
        order=order,
        **links,
    )


def _add_sections(db: Session, subject: Subject, sections) -> None:
    for s_order, (title_ru, title_tj, topics) in enumerate(sections, start=1):
        section = Topic(subject=subject, title_ru=title_ru, title_tj=title_tj, order=s_order)
        db.add(section)
        for t_order, data in enumerate(topics, start=1):
            _add_topic(db, subject, section, t_order, data)


def seed_achievements(db: Session) -> None:
    existing = set(db.scalars(select(Achievement.code)).all())
    for data in ACHIEVEMENTS_SEED:
        if data["code"] not in existing:
            db.add(Achievement(**data))


def seed_superadmin(db: Session) -> None:
    email, password = settings.FIRST_SUPERADMIN_EMAIL, settings.FIRST_SUPERADMIN_PASSWORD
    if not email or not password:
        return
    user = db.scalar(select(User).where(User.email == email.lower()))
    if user is None:
        db.add(User(email=email.lower(), name="Admin", password_hash=get_password_hash(password),
                    admin_role=AdminRole.SUPERADMIN))
        print(f"Superadmin {email} created")
    elif user.admin_role != AdminRole.SUPERADMIN:
        user.admin_role = AdminRole.SUPERADMIN


def seed_content(
    db: Session, own_dir: Optional[Path] = None, lessons_dir: Optional[Path] = None,
) -> None:
    subjects = seed_structure(db)

    # Short theory (lessons with mini-checks) for some abiturient subjects
    if not db.scalar(select(Lesson.id).join(Topic).where(Topic.subject_id == subjects["math"].id)):
        for code, sections in THEORY.items():
            _add_sections(db, subjects[code], [(f"Краткая теория: {ru}", f"Назария: {tj}", topics)
                                               for ru, tj, topics in sections])

    if not db.scalar(select(Subject.id).where(Subject.grade.is_not(None))):
        for grade, school_subjects in SCHOOL.items():
            for order, (title_ru, title_tj, icon, color, sections) in enumerate(school_subjects, start=1):
                subject = Subject(grade=grade, title_ru=title_ru, title_tj=title_tj, icon=icon, color=color,
                                  order=order)
                db.add(subject)
                _add_sections(db, subject, sections)

    count = seed_own_bank(db, subjects, load_own_banks(own_dir))
    if count:
        print(f"Own tasks loaded: {count}")

    count = seed_lessons(db, subjects, load_lesson_banks(lessons_dir))
    if count:
        print(f"Lessons loaded: {count}")


def run() -> None:
    with SessionLocal() as db:
        seed_achievements(db)
        seed_superadmin(db)
        seed_content(db)
        db.commit()
    print("Seed finished")


if __name__ == "__main__":
    sys.argv = sys.argv[:1]
    run()
